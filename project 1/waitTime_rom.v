`timescale 10ns / 1ns
/* ------------------------  Module Declarations ----------------------------- */
module waitTime_rom (addr, data);
// ------------------------ Parameter Declarations --------------------------- //
// -------------------------- Inputs Declarations ---------------------------- //
  // ROM address - 5 bits. - represent the Customers and Tellers inputs.  
  input [4:0] addr; 
// ------------------------- Outputs Declarations ---------------------------- //
// ROM data - represent two digits for waiting time in binary format. 
  output [7:0] data;
// --------------------------- Wire Declarations ----------------------------- //
// ---------------------------- Reg Declarations ----------------------------- //
 reg [7:0] arom [0:31];
// --------------------------------------------------------------------------- //
// ---------------------------- Initial setup  ------------------------------- //
  initial
  $readmemb("waitTime_rom.txt", arom);
// --------------------------------------------------------------------------- //
// ------------------------- Instantiation Modules --------------------------- //
// --------------------------------------------------------------------------- //
// ----------------------- Combinational Logic  ------------------------------ //
  assign data = arom[addr]; 
// --------------------------------------------------------------------------- //
// ----------------------- Sequential  Logic  -------------------------------- //
// --------------------------------------------------------------------------- //
// --------------------------------------------------------------------------- //
endmodule
